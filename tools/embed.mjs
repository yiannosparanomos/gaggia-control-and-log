// Turns web/dist/index.html into firmware/src/web_assets.h (gzipped byte array).
// Run automatically by `npm run build` in web/.
import { readFileSync, writeFileSync } from 'node:fs';
import { gzipSync } from 'node:zlib';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const html = readFileSync(join(root, 'web/dist/index.html'));
const gz = gzipSync(html, { level: 9 });

const bytes = [];
for (let i = 0; i < gz.length; i += 16) {
  bytes.push('  ' + Array.from(gz.subarray(i, i + 16), (b) => '0x' + b.toString(16).padStart(2, '0')).join(', '));
}

const out = `// GENERATED by tools/embed.mjs from web/ — do not edit by hand. Run \`npm run build\` in web/.
// ${html.length} bytes of HTML, ${gz.length} bytes gzipped.
// html sha256: ${createHash('sha256').update(html).digest('hex')}
#pragma once
#include <Arduino.h>

const size_t INDEX_HTML_GZ_LEN = ${gz.length};
const uint8_t INDEX_HTML_GZ[] PROGMEM = {
${bytes.join(',\n')}
};
`;
writeFileSync(join(root, 'firmware/src/web_assets.h'), out);
console.log(`web_assets.h: ${html.length} B html -> ${gz.length} B gzip`);
